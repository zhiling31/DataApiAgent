    def auto_fetch_bts_geospatial_data_catalog(self, **kwargs):
        """
        BTS Geospatial Data Catalog (data.transportation.gov) 元数据抓取。

        条目级: GET /api/views/{uuid}
        集合级: GET /data.json → 按 contactPoint (ntad@dot.gov) + 文本过滤
        """
        import json

        BASE = "https://data.transportation.gov"

        # ── 条目级 ──
        dataset_id = kwargs.get('uuid') or kwargs.get('official_website_id')
        if dataset_id:
            resp = self._get_with_retry(f"{BASE}/api/views/{dataset_id}")
            txt = resp.text if hasattr(resp, 'text') else str(resp)
            try:
                return {"source": "BTS-Geospatial-Catalog", "data": json.loads(txt)}
            except json.JSONDecodeError:
                return {"error": f"Views API non-JSON: {txt[:300]}"}

        # ── 集合级 ──
        shortname = (kwargs.get('dataset_shortname') or '').strip()
        doi = (kwargs.get('doi') or '').strip()
        if not shortname and not doi:
            return {"error": "Provide uuid, dataset_shortname, or doi."}

        resp = self._get_with_retry(f"{BASE}/data.json")
        txt = resp.text if hasattr(resp, 'text') else str(resp)
        try:
            catalog = json.loads(txt)
        except json.JSONDecodeError:
            return {"error": f"data.json non-JSON: {txt[:300]}"}

        datasets = catalog.get('dataset', [])
        terms = [t.lower() for t in (shortname, doi) if t]

        matched = []
        for ds in datasets:
            email = (ds.get('contactPoint', {}).get('hasEmail', '') or '').lower()
            if 'ntad@dot.gov' in email:
                matched.append(ds)
                continue
            if any(t in json.dumps(ds).lower() for t in terms):
                matched.append(ds)

        return {
            "source": "BTS-Geospatial-Catalog",
            "data": {
                "catalog_context": catalog.get('describedBy', ''),
                "total_catalog_size": len(datasets),
                "matched_count": len(matched),
                "search_terms": terms,
                "datasets": matched,
            },
        }

    def auto_fetch_zenodo(self, **kwargs):
        """
        从 Zenodo REST API 获取数据集完整集合级元数据。
    
        支持参数:
          - dataset_url:  Zenodo 数据集页面 URL
          - doi:          Zenodo DOI (如 10.5281/zenodo.17260370)
          - uuid / official_website_id: Zenodo record ID
    
        返回: {"source": "Zenodo-Custom", "data": dict} 或 {"error": "..."}
        """
        import re
        import requests as req

        record_id = kwargs.get('uuid') or kwargs.get('official_website_id') or None
    
        if not record_id:
            dataset_url = kwargs.get('dataset_url', '')
            doi = kwargs.get('doi', '')
            if dataset_url:
                m = re.search(r'zenodo\.org/(?:records?|api/records)/(\d+)', dataset_url)
                if m:
                    record_id = m.group(1)
            if not record_id and doi:
                m = re.search(r'zenodo[./](\d+)', doi)
                if m:
                    record_id = m.group(1)
    
        if not record_id:
            return {"error": "无法从提供的参数中提取 Zenodo record ID。"}
    
        api_url = "https://zenodo.org/api/records/" + str(record_id)
        headers = {'User-Agent': 'Mozilla/5.0 (compatible; MetadataFetcher/1.0)'}
    
        for attempt in range(3):
            try:
                resp = req.get(api_url, headers=headers, timeout=30)
                if resp.status_code == 200:
                    return {"source": "Zenodo-Custom", "data": resp.json()}
                elif resp.status_code == 404:
                    return {"error": "Zenodo record " + str(record_id) + " 未找到。"}
                elif resp.status_code in (401, 403):
                    return {"error": "Zenodo API 需要鉴权 (HTTP " + str(resp.status_code) + ")。"}
                else:
                    return {"error": "Zenodo API 返回非预期状态码: " + str(resp.status_code)}
            except req.RequestException as e:
                if attempt == 2:
                    return {"error": "请求 Zenodo API 时发生网络异常: " + str(e)}
    
        return {"error": "请求 Zenodo API 失败。"}

    def auto_fetch_figshare(self, **kwargs):
        """
        Fetch collection-level or article-level metadata from Figshare API v2.

        Three access paths (priority order):
          1. collection_id  -> GET /v2/collections/{id}
          2. article_id     -> GET /v2/articles/{id}
          3. doi            -> parse figshare article ID from DOI, then GET article

        The API returns DataCite-compliant metadata: title, authors, doi,
        description, categories, tags, license, files, published_date, etc.
        """
        import re as _re
        BASE = "https://api.figshare.com/v2"
        custom_headers = {"Accept": "application/json"}
        data = None

        # Priority 1: Collection ID
        collection_id = kwargs.get("collection_id") or kwargs.get("uuid")
        if collection_id is not None:
            url = f"{BASE}/collections/{collection_id}"
            try:
                resp = self._get_with_retry(url, headers=custom_headers)
                data = resp.json() if hasattr(resp, 'json') else resp
            except Exception as e:
                return {"error": f"Figshare collection fetch failed: {str(e)}"}

        # Priority 2: Article ID
        if data is None:
            article_id = kwargs.get("article_id") or kwargs.get("official_website_id")
            if article_id is not None:
                url = f"{BASE}/articles/{article_id}"
                try:
                    resp = self._get_with_retry(url, headers=custom_headers)
                    data = resp.json() if hasattr(resp, 'json') else resp
                except Exception as e:
                    return {"error": f"Figshare article fetch failed: {str(e)}"}

        # Priority 3: DOI -> parse article ID from figshare DOI pattern
        if data is None:
            doi = kwargs.get("doi")
            if doi:
                # Figshare DOIs: 10.6084/m9.figshare.{article_id} or .{article_id}.v{version}
                match = _re.search(r'figshare[./]([0-9]+)', doi)
                if match:
                    article_id = int(match.group(1))
                    url = f"{BASE}/articles/{article_id}"
                    try:
                        resp = self._get_with_retry(url, headers=custom_headers)
                        data = resp.json() if hasattr(resp, 'json') else resp
                    except Exception as e:
                        return {"error": f"Figshare article (from DOI) fetch failed: {str(e)}"}
                else:
                    return {"error": f"Could not extract figshare article ID from DOI: {doi}"}

        if data is None:
            return {"error": "Must provide collection_id, article_id, or doi"}

        # Normalize: collections use "resource_title"; articles use "title"
        if "title" not in data and "resource_title" in data:
            data["title"] = data["resource_title"]

        # Extract primary author string from authors list
        authors = data.get("authors", [])
        if authors and isinstance(authors, list) and len(authors) > 0:
            data["author"] = authors[0].get("full_name", "")

        return {"source": "figshare-Custom", "data": data}

    def auto_fetch_noaa_national_centers_for_environmental_information__ncei_(self, **kwargs):
        """
        获取 NOAA NCEI (NGDC) 数据集的 ISO 19115-2 XML 元数据。

        原生 API: NOAA NGDC metadata published XML endpoint
        URL: https://www.ngdc.noaa.gov/metadata/published/{xml_path}

        参数提取瀑布流：
        1. 从 doi_landing_page 的 xml= 参数提取 (最可靠)
        2. 从 doi_landing_page HTML 中提取 NCEI Metadata ID
        3. 从 dataset_url HTML 中提取 NCEI Metadata ID
        """
        import re
        from urllib.parse import unquote

        doi_landing_page = kwargs.get('doi_landing_page', '')
        dataset_url = kwargs.get('dataset_url', '')
        doi = kwargs.get('doi', '')

        xml_path = None

        # --- 策略 1: 从 doi_landing_page 的 xml= 参数提取 ---
        if doi_landing_page:
            match = re.search(r'[?&]xml=([^&]+)', doi_landing_page)
            if match:
                raw_path = unquote(match.group(1))
                xml_path = re.sub(r'/+', '/', raw_path).strip('/')

        # --- 策略 2: 抓取 doi_landing_page HTML 提取 NCEI Metadata ID ---
        if not xml_path and doi_landing_page:
            try:
                html = self._get_with_retry(doi_landing_page).text
                id_match = re.search(
                    r'NCEI\s+Metadata\s+ID:\s*([\w.:-]+)',
                    html, re.IGNORECASE
                )
                if id_match:
                    ncei_id = id_match.group(1)
                    parts = ncei_id.split(':')
                    if len(parts) >= 2:
                        shortname = parts[-1]
                        xml_link = re.search(r'[?&]xml=([^&"]+)', html)
                        if xml_link:
                            raw_path = unquote(xml_link.group(1))
                            xml_path = re.sub(r'/+', '/', raw_path).strip('/')
                        else:
                            xml_path = (
                                f"NOAA/NESDIS/NGDC/MGG/DEM/iso/xml/{shortname}.xml"
                            )
            except Exception:
                pass

        # --- 策略 3: 抓取 dataset_url HTML 提取 NCEI Metadata ID ---
        if not xml_path and dataset_url:
            try:
                html = self._get_with_retry(dataset_url).text
                landing_match = re.search(
                    r'/access/metadata/landing-page/bin/iso\?id=([^"&\s#]+)',
                    html
                )
                if landing_match:
                    ncei_id = unquote(landing_match.group(1))
                    parts = ncei_id.split(':')
                    if len(parts) >= 2:
                        shortname = parts[-1]
                        xml_link = re.search(r'[?&]xml=([^&"]+)', html)
                        if xml_link:
                            raw_path = unquote(xml_link.group(1))
                            xml_path = re.sub(r'/+', '/', raw_path).strip('/')
                        else:
                            xml_path = (
                                f"NOAA/NESDIS/NGDC/MGG/DEM/iso/xml/{shortname}.xml"
                            )
            except Exception:
                pass

        if not xml_path:
            return {
                "error": (
                    "缺少关键参数，无法解析出内部 XML 路径。"
                    "请提供 doi_landing_page 参数（形如 "
                    "https://data.noaa.gov/metaview/page?xml=...），"
                    "或包含 NCEI Metadata ID 链接的 dataset_url。"
                )
            }

        api_url = f"https://www.ngdc.noaa.gov/metadata/published/{xml_path}"

        try:
            response = self._get_with_retry(api_url)
            response.raise_for_status()
        except Exception as e:
            return {
                "error": f"获取元数据失败: {str(e)}",
                "api_url": api_url
            }

        return {
            "source": "NOAA NCEI (NGDC)",
            "format": "xml",
            "data": response.text
        }

