    def auto_fetch_zenodo(self, **kwargs):
        """
        从 Zenodo REST API 获取数据集完整集合级元数据。
    
        支持参数:
          - dataset_url:  Zenodo 数据集页面 URL
          - doi:          Zenodo DOI (如 10.5281/zenodo.17260370)
          - uuid / official_website_id: Zenodo record ID
    
        返回: {"source": "Zenodo-Custom", "data": dict} 或 {"error": "..."}
        """
        import re
        import requests as req

        record_id = kwargs.get('uuid') or kwargs.get('official_website_id') or None
    
        if not record_id:
            dataset_url = kwargs.get('dataset_url', '')
            doi = kwargs.get('doi', '')
            if dataset_url:
                m = re.search(r'zenodo\.org/(?:records?|api/records)/(\d+)', dataset_url)
                if m:
                    record_id = m.group(1)
            if not record_id and doi:
                m = re.search(r'zenodo[./](\d+)', doi)
                if m:
                    record_id = m.group(1)
    
        if not record_id:
            return {"error": "无法从提供的参数中提取 Zenodo record ID。"}
    
        api_url = "https://zenodo.org/api/records/" + str(record_id)
        headers = {'User-Agent': 'Mozilla/5.0 (compatible; MetadataFetcher/1.0)'}
    
        for attempt in range(3):
            try:
                resp = req.get(api_url, headers=headers, timeout=30)
                if resp.status_code == 200:
                    return {"source": "Zenodo-Custom", "data": resp.json()}
                elif resp.status_code == 404:
                    return {"error": "Zenodo record " + str(record_id) + " 未找到。"}
                elif resp.status_code in (401, 403):
                    return {"error": "Zenodo API 需要鉴权 (HTTP " + str(resp.status_code) + ")。"}
                else:
                    return {"error": "Zenodo API 返回非预期状态码: " + str(resp.status_code)}
            except req.RequestException as e:
                if attempt == 2:
                    return {"error": "请求 Zenodo API 时发生网络异常: " + str(e)}
    
        return {"error": "请求 Zenodo API 失败。"}

    def auto_fetch_figshare(self, **kwargs):
        """
        Fetch collection-level or article-level metadata from Figshare API v2.

        Three access paths (priority order):
          1. collection_id  -> GET /v2/collections/{id}
          2. article_id     -> GET /v2/articles/{id}
          3. doi            -> parse figshare article ID from DOI, then GET article

        The API returns DataCite-compliant metadata: title, authors, doi,
        description, categories, tags, license, files, published_date, etc.
        """
        import re as _re
        BASE = "https://api.figshare.com/v2"
        custom_headers = {"Accept": "application/json"}
        data = None

        # Priority 1: Collection ID
        collection_id = kwargs.get("collection_id") or kwargs.get("uuid")
        if collection_id is not None:
            url = f"{BASE}/collections/{collection_id}"
            try:
                resp = self._get_with_retry(url, headers=custom_headers)
                data = resp.json() if hasattr(resp, 'json') else resp
            except Exception as e:
                return {"error": f"Figshare collection fetch failed: {str(e)}"}

        # Priority 2: Article ID
        if data is None:
            article_id = kwargs.get("article_id") or kwargs.get("official_website_id")
            if article_id is not None:
                url = f"{BASE}/articles/{article_id}"
                try:
                    resp = self._get_with_retry(url, headers=custom_headers)
                    data = resp.json() if hasattr(resp, 'json') else resp
                except Exception as e:
                    return {"error": f"Figshare article fetch failed: {str(e)}"}

        # Priority 3: DOI -> parse article ID from figshare DOI pattern
        if data is None:
            doi = kwargs.get("doi")
            if doi:
                # Figshare DOIs: 10.6084/m9.figshare.{article_id} or .{article_id}.v{version}
                match = _re.search(r'figshare[./]([0-9]+)', doi)
                if match:
                    article_id = int(match.group(1))
                    url = f"{BASE}/articles/{article_id}"
                    try:
                        resp = self._get_with_retry(url, headers=custom_headers)
                        data = resp.json() if hasattr(resp, 'json') else resp
                    except Exception as e:
                        return {"error": f"Figshare article (from DOI) fetch failed: {str(e)}"}
                else:
                    return {"error": f"Could not extract figshare article ID from DOI: {doi}"}

        if data is None:
            return {"error": "Must provide collection_id, article_id, or doi"}

        # Normalize: collections use "resource_title"; articles use "title"
        if "title" not in data and "resource_title" in data:
            data["title"] = data["resource_title"]

        # Extract primary author string from authors list
        authors = data.get("authors", [])
        if authors and isinstance(authors, list) and len(authors) > 0:
            data["author"] = authors[0].get("full_name", "")

        return {"source": "figshare-Custom", "data": data}

    def auto_fetch_noaa_national_centers_for_environmental_information__ncei_(self, **kwargs):
        import re
        import urllib.parse
    
        doi = kwargs.get('doi')
        dataset_url = kwargs.get('dataset_url')
        doi_landing_page = kwargs.get('doi_landing_page')
        dataset_name = kwargs.get('dataset_name')
    
        metadata_id = None
    
        # Strategy 1: Extract from doi_landing_page URL pattern
        # Pattern: ...?xml=.../iso/xml/{name}.xml&...
        if doi_landing_page:
            m = re.search(r'/iso/xml/([^/.&]+)\.xml', doi_landing_page)
            if m:
                name = m.group(1)
                metadata_id = f"gov.noaa.ngdc.mgg.dem:{name}"
    
        # Strategy 2: Scrape doi_landing_page for NCEI Metadata ID
        if not metadata_id and doi_landing_page:
            try:
                resp = self._get_with_retry(doi_landing_page)
                m = re.search(r'NCEI\s+Metadata\s+ID:\s*(gov\.noaa\.[^\s<]+)', resp.text)
                if m:
                    metadata_id = m.group(1)
            except Exception:
                pass
    
        # Strategy 3: Scrape dataset_url for NCEI Metadata ID
        if not metadata_id and dataset_url:
            try:
                resp = self._get_with_retry(dataset_url)
                m = re.search(r'NCEI\s+Metadata\s+ID:\s*(gov\.noaa\.[^\s<]+)', resp.text)
                if m:
                    metadata_id = m.group(1)
            except Exception:
                pass
    
        if not metadata_id:
            return {"error": "无法从已知参数中解析出 NCEI Metadata ID"}
    
        # Use NCEI Geoportal REST API (first priority: /rest/ path)
        api_url = f"https://www.ncei.noaa.gov/metadata/geoportal/rest/metadata/item/{metadata_id}/xml"
    
        resp = self._get_with_retry(api_url)
    
        return {
            "source": "NOAA NCEI",
            "format": "xml",
            "data": resp.text
        }

    def auto_fetch_icos(self, **kwargs):
        import urllib.parse
        import re
    
        # ============================================================
        # Polymorphic DOI extraction (multi-path waterfall)
        # ============================================================
        doi = kwargs.get('doi')
    
        # Path 1: Direct DOI
        if doi:
            doi = doi.strip()
        # Path 2: Regex from URL strings
        elif kwargs.get('doi_landing_page') or kwargs.get('dataset_url'):
            for source in [kwargs.get('doi_landing_page', ''), kwargs.get('dataset_url', '')]:
                if not source:
                    continue
                m = re.search(r'10\.\d{4,}/[^\s"\'<>?#]+', source)
                if m:
                    doi = m.group(0).rstrip('.').rstrip(',')
                    break
        # Path 3: Scrape HTML meta from doi_landing_page for DOI
        if not doi and kwargs.get('doi_landing_page'):
            try:
                landing_url = kwargs['doi_landing_page']
                resp = self._get_with_retry(landing_url)
                html = resp.text
                for pattern in [
                    r'data doi[:\s]*10\.\d{4,}/[^\s"\'<>]+',
                    r'doi[:\s]*10\.\d{4,}/[^\s"\'<>]+',
                    r'10\.\d{4,}/[^\s"\'<>?#]+',
                ]:
                    m = re.search(pattern, html, re.IGNORECASE)
                    if m:
                        doi_match = re.search(r'10\.\d{4,}/[^\s"\'<>?#]+', m.group(0))
                        if doi_match:
                            doi = doi_match.group(0).rstrip('.').rstrip(',')
                            break
            except Exception:
                pass
    
        if not doi:
            return {"error": "Cannot determine DOI. Provide 'doi', 'dataset_url', or 'doi_landing_page'."}
    
        doi_lower = doi.strip().lower()
    
        # ============================================================
        # Step 1: SPARQL lookup: DOI -> collection URI
        # ============================================================
        sparql_query = (
            "PREFIX cpmeta: <http://meta.icos-cp.eu/ontologies/cpmeta/> "
            "SELECT ?coll WHERE { "
            "  ?coll a cpmeta:Collection . "
            "  ?coll cpmeta:hasDoi ?doi . "
            f'  FILTER(LCASE(STR(?doi)) = "{doi_lower}") '
            "} LIMIT 1"
        )
        sparql_url = "https://meta.icos-cp.eu/sparql?" + urllib.parse.urlencode({
            "query": sparql_query,
            "format": "json"
        })
    
        sparql_resp = self._get_with_retry(sparql_url)
        try:
            sparql_data = sparql_resp.json()
        except Exception:
            return {"error": "SPARQL endpoint returned non-JSON response."}
    
        bindings = sparql_data.get("results", {}).get("bindings", [])
        if not bindings:
            return {"error": f"No collection found in ICOS Carbon Portal for DOI: {doi}"}
    
        coll_uri = bindings[0]["coll"]["value"]
        coll_id = coll_uri.rsplit('/', 1)[-1]
    
        # ============================================================
        # Step 2: Primary RESTful API - collection landing page
        # ============================================================
        coll_url = f"https://meta.icos-cp.eu/collections/{coll_id}"
        headers = {"Accept": "application/json"}
        coll_resp = self._get_with_retry(coll_url, headers=headers)
    
        try:
            coll_data = coll_resp.json()
        except Exception:
            return {"error": f"Failed to parse JSON from {coll_url}", "raw": coll_resp.text[:500]}
    
        return {
            "source": "ICOS",
            "format": "json",
            "data": coll_data
        }

    def auto_fetch_nasa_earthdata__socioeconomic_data_and_applications_center___sedac_(self, **kwargs):
        """
        Fetch collection-level metadata from NASA Earthdata CMR for SEDAC datasets.
    
        Uses the CMR (Common Metadata Repository) API: 
        - Resolves DOI or URL to a concept ID via CMR search
        - Retrieves full UMM-JSON metadata via the concept endpoint
        """
        import re
        import urllib.parse
    
        doi = kwargs.get('doi')
        dataset_url = kwargs.get('dataset_url') or kwargs.get('doi_landing_page')
    
        concept_id = None
    
        # --- Polymorphic parameter resolution: resolve concept ID ---
        # Path 1: Use DOI to search CMR collections
        if doi:
            search_url = (
                "https://cmr.earthdata.nasa.gov/search/collections.umm_json"
                f"?doi={urllib.parse.quote(doi, safe='')}"
            )
            try:
                search_resp = self._get_with_retry(search_url)
                search_data = search_resp.json()
                items = search_data.get('items', [])
                if items and len(items) > 0:
                    concept_id = items[0].get('meta', {}).get('concept-id')
            except Exception:
                pass
    
        # Path 2: If no DOI, extract slug from URL and search CMR by entry_id
        if not concept_id and dataset_url:
            # Extract the last meaningful path segment from Earthdata catalog URL
            # e.g. ".../catalog/sedac-ciesin-sedac-gpwv4-popdens-r11-4.11"
            match = re.search(
                r'/catalog/(?:sedac-)?([a-zA-Z0-9]+(?:-[a-zA-Z0-9]+)+'
                r'(?:-r\d+)?(?:-\d+\.\d+)?)',
                dataset_url
            )
            if match:
                raw_slug = match.group(1)
                # Transform to CMR entry_id format: lowercase with underscores
                entry_id = raw_slug.upper().replace('-', '_')
                search_url = (
                    "https://cmr.earthdata.nasa.gov/search/collections.umm_json"
                    f"?entry_id={entry_id}"
                )
                try:
                    search_resp = self._get_with_retry(search_url)
                    search_data = search_resp.json()
                    items = search_data.get('items', [])
                    if items and len(items) > 0:
                        concept_id = items[0].get('meta', {}).get('concept-id')
                except Exception:
                    pass
    
        # Path 3: Try broader URL extraction - just grab the catalog slug portion
        if not concept_id and dataset_url:
            match = re.search(r'/catalog/([^/\s?#]+)', dataset_url)
            if match:
                raw_slug = match.group(1)
                # Remove leading 'sedac-' if present, then transform
                if raw_slug.lower().startswith('sedac-'):
                    raw_slug = raw_slug[6:]
                # Try entry_id and short_name searches
                candidate = raw_slug.upper().replace('-', '_')
                for param in ['entry_id', 'short_name']:
                    search_url = (
                        "https://cmr.earthdata.nasa.gov/search/collections.umm_json"
                        f"?{param}={candidate}"
                    )
                    try:
                        search_resp = self._get_with_retry(search_url)
                        search_data = search_resp.json()
                        items = search_data.get('items', [])
                        if items and len(items) > 0:
                            concept_id = items[0].get('meta', {}).get('concept-id')
                            break
                    except Exception:
                        continue
    
        if not concept_id:
            return {
                "error": (
                    "无法解析出 CMR concept ID。请提供有效的 DOI 或包含 "
                    "Earthdata catalog slug 的 dataset_url。"
                )
            }
    
        # --- Final API: CMR Concept endpoint (UMM-JSON) ---
        # This is the most data-rich, native RESTful API for a single collection
        concept_url = (
            "https://cmr.earthdata.nasa.gov/search/concepts"
            f"/{concept_id}.umm_json"
        )
        resp = self._get_with_retry(concept_url)
    
        return {
            "source": "NASA Earthdata CMR",
            "format": "json",
            "data": resp.json()
        }

    def auto_fetch_laads_daac(self, **kwargs):
        import re
    
        dataset_url = kwargs.get('dataset_url', '')
        doi_landing_page = kwargs.get('doi_landing_page', '')
        dataset_name = kwargs.get('dataset_name', '')
    
        short_name = None
    
        # 路径1: 从 dataset_url 提取 short_name
        if dataset_url:
            m = re.search(r'/products/([A-Za-z0-9_-]+)', dataset_url)
            if m:
                short_name = m.group(1)
    
        # 路径2: 从 doi_landing_page 提取 short_name
        if not short_name and doi_landing_page:
            m = re.search(r'/products/([A-Za-z0-9_-]+)', doi_landing_page)
            if m:
                short_name = m.group(1)
    
        # 路径3: 直接使用 dataset_name 作为 short_name
        if not short_name and dataset_name:
            short_name = dataset_name.strip()
    
        if not short_name:
            return {"error": "缺少关键参数，无法解析出产品 short_name。请提供 dataset_url、doi_landing_page 或 dataset_name。"}
    
        # 使用 CMR UMM-JSON 格式 API 获取集合级元数据
        # CMR 是 NASA EOSDIS 的中央元数据仓库，LAADS DAAC 的所有产品元数据均注册于此
        url = f"https://cmr.earthdata.nasa.gov/search/collections.umm_json?short_name={short_name}"
    
        response = self._get_with_retry(url)
    
        return {
            "source": "NASA CMR (LAADS DAAC)",
            "format": "json",
            "data": response.json()
        }

    def auto_fetch_rosap__national_transportation_library_(self, **kwargs):
        import re
    
        # 获取入参
        dataset_url = kwargs.get('dataset_url', '')
        doi_landing_page = kwargs.get('doi_landing_page', '')
        doi = kwargs.get('doi', '')
    
        # 内部数字ID
        internal_numeric_id = None
    
        # 瀑布流1: 从 doi_landing_page 正则提取
        if doi_landing_page:
            match = re.search(r'/view/dot/(\d+)', doi_landing_page)
            if match:
                internal_numeric_id = match.group(1)
    
        # 瀑布流2: 从 dataset_url 正则提取
        if not internal_numeric_id and dataset_url:
            match = re.search(r'/view/dot/(\d+)', dataset_url)
            if match:
                internal_numeric_id = match.group(1)
    
        # 瀑布流3: 通过DOI解析获取ROSAP落地页URL
        if not internal_numeric_id and doi:
            doi_resolve_url = f'https://doi.org/{doi}'
            try:
                resp = self._get_with_retry(doi_resolve_url, headers={'Accept': 'text/html'})
                # self._get_with_retry 返回的是 requests.Response 对象
                final_url = ''
                if hasattr(resp, 'url'):
                    final_url = resp.url
                elif hasattr(resp, 'headers'):
                    final_url = resp.headers.get('Location', '')
                if final_url:
                    match = re.search(r'/view/dot/(\d+)', final_url)
                    if match:
                        internal_numeric_id = match.group(1)
            except Exception:
                pass
    
        if not internal_numeric_id:
            return {"error": "缺少关键参数，无法解析出内部ID。需要包含 rosap.ntl.bts.gov/view/dot/{id} 格式的URL或有效DOI。"}
    
        # 构建OAI-PMH identifier: oai:dot.stacks:dot:{numeric_id}
        oai_identifier = f"oai:dot.stacks:dot:{internal_numeric_id}"
    
        # 请求OAI-PMH GetRecord
        api_url = f"https://rosap.ntl.bts.gov/fedora/oai?verb=GetRecord&identifier={oai_identifier}&metadataPrefix=oai_dc"
    
        response = self._get_with_retry(api_url)
    
        return {
            "source": "ROSAP (National Transportation Library)",
            "format": "xml",
            "data": response.text
        }

    def auto_fetch_registry_of_open_data_on_aws(self, **kwargs):
        """
        Fetch collection-level dataset metadata from Registry of Open Data on AWS (RODA).
    
        The RODA hosts dataset metadata as YAML files at:
        https://registry.opendata.aws/datasets/awslabs-open-data-registry/datasets/{slug}.yaml
    
        This function extracts the dataset slug from the provided URL/landing page
        and fetches the corresponding YAML metadata.
        """
        import re
    
        dataset_url = kwargs.get('dataset_url', '')
        doi_landing_page = kwargs.get('doi_landing_page', '')
        dataset_name = kwargs.get('dataset_name', '')
    
        # --- Step 1: Extract the dataset slug ---
        slug = None
    
        # Priority 1: Extract from dataset_url (e.g., https://registry.opendata.aws/overture/)
        if dataset_url:
            match = re.search(r'registry\.opendata\.aws/([^/]+)', dataset_url)
            if match:
                slug = match.group(1)
    
        # Priority 2: Extract from doi_landing_page
        if not slug and doi_landing_page:
            match = re.search(r'registry\.opendata\.aws/([^/]+)', doi_landing_page)
            if match:
                slug = match.group(1)
    
        # Priority 3: Derive from dataset_name (lowercase, replace spaces with hyphens)
        if not slug and dataset_name:
            slug = dataset_name.lower().strip()
            slug = re.sub(r'[^a-z0-9]+', '-', slug)
            slug = slug.strip('-')
    
        if not slug:
            return {"error": "无法从提供的参数中解析出 dataset slug，需要 registry.opendata.aws 格式的 URL 或 landing page。"}
    
        # --- Step 2: Construct the YAML API URL ---
        api_url = f"https://registry.opendata.aws/datasets/awslabs-open-data-registry/datasets/{slug}.yaml"
    
        # --- Step 3: Fetch the YAML metadata ---
        try:
            response = self._get_with_retry(api_url)
            response.raise_for_status()
            yaml_text = response.text
        
            # Validate that we got meaningful YAML (not an HTML error page)
            if not yaml_text or yaml_text.strip().startswith('<!DOCTYPE') or yaml_text.strip().startswith('<html'):
                return {"error": f"API 返回了 HTML 而非 YAML，slug '{slug}' 可能不匹配任何数据集。"}
        
            return {
                "source": "Registry of Open Data on AWS",
                "format": "yaml",
                "data": yaml_text
            }
        
        except Exception as e:
            return {"error": f"请求 YAML API 失败: {str(e)}"}

