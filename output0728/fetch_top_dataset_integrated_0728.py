class IntegratedDataRepoFetcher:
    """自动生成的数据存储库 API 抓取类"""
    def __init__(self):
        # 移除了 User-Agent，因为 impersonate 会在底层自动生成最完美的浏览器 UA
        self.headers = {
            "Accept": "application/json, application/xml, text/yaml, */*"
        }

    def _get_with_retry(self, url, headers=None, max_retries=3):
        if headers is None: headers = self.headers
        for attempt in range(max_retries):
            try:
                # 🌟 核心修改 2：加入 impersonate="chrome120"，物理级绕过 WAF 防火墙
                response = requests.get(
                    url, 
                    headers=headers, 
                    timeout=15, 
                    verify=False,
                    impersonate="chrome120"
                )
                
                # HTTP/403 依然会抛出异常，触发重试
                if response.status_code >= 400:
                    response.raise_for_status()
                    
                return response
                
            # 🌟 核心修改 3：将 requests.exceptions 改为拦截基类 Exception
            # 因为 curl_cffi 的底层异常类与原生 requests 不同，拦截 Exception 保证重试机制不失效
            except Exception as e:
                if attempt < max_retries - 1:
                    time.sleep(2 ** attempt)
                else:
                    raise Exception(f"已达到最大重试次数 ({max_retries})，最终失败: {e}")

