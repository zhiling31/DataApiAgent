    def auto_fetch_open_government_portal(self, **kwargs):
        import re
        import json
        import urllib.parse

        dataset_url = kwargs.get("dataset_url") or ""
        landing_page = kwargs.get("doi_landing_page") or ""
        dataset_name = kwargs.get("dataset_name") or ""
        doi = kwargs.get("doi") or ""

        dataset_id = None

        uuid_re = re.compile(r"/dataset/([0-9a-fA-F-]{36})")
        for candidate_url in (dataset_url, landing_page, doi):
            if candidate_url:
                match = uuid_re.search(candidate_url)
                if match:
                    dataset_id = match.group(1)
                    break

        if not dataset_id and dataset_name:
            search_query = urllib.parse.urlencode(
                {"q": 'name:"%s"' % dataset_name, "rows": 1}
            )
            search_url = (
                "https://open.canada.ca/data/api/3/action/package_search?"
                + search_query
            )
            try:
                search_resp = self._get_with_retry(search_url)
                try:
                    search_json = search_resp.json()
                except (json.JSONDecodeError, AttributeError):
                    search_json = {}
                results = (
                    search_json.get("result", {}).get("results", [])
                    if isinstance(search_json, dict)
                    else []
                )
                if results and len(results) > 0:
                    dataset_id = results[0].get("id")
            except Exception:
                dataset_id = None

        if not dataset_id:
            return {"error": "缺少关键参数，无法解析出内部 ID"}

        api_url = (
            "https://open.canada.ca/data/api/3/action/package_show?id="
            + urllib.parse.quote(dataset_id, safe="")
        )
        resp = self._get_with_retry(api_url)

        try:
            data = resp.json()
        except (json.JSONDecodeError, AttributeError):
            data = resp.text

        return {
            "source": "Open Government Portal (open.canada.ca)",
            "format": "json",
            "data": data,
        }

    def auto_fetch_nerc_eds_national_geoscience_data_centre(self, **kwargs):
        import re
        from urllib.parse import urlencode

        doi = kwargs.get('doi') or ''
        dataset_url = kwargs.get('dataset_url') or ''
        doi_landing_page = kwargs.get('doi_landing_page') or ''

        # --- 1. Extract the DOI suffix UUID (ed322978-...) from doi / url / landing page ---
        doi_uuid = None
        if doi:
            m = re.search(r'10\.5285/([0-9a-fA-F-]{36})', doi)
            if m:
                doi_uuid = m.group(1)
        uuid_re = re.compile(r'[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}')
        if not doi_uuid:
            for candidate in (dataset_url, doi_landing_page):
                if candidate:
                    m = uuid_re.search(candidate)
                    if m:
                        doi_uuid = m.group(0)
                        break
        if not doi_uuid:
            return {"error": "缺少关键参数，无法解析出内部 ID（DOI UUID）"}

        # --- 2. Dynamic mapping: DOI UUID -> GeoNetwork internal fileIdentifier via CSW ---
        # The CSW/Lucene index tokenises hyphenated strings, so use the first UUID segment
        # as the search token (it is the leading DOI suffix segment and is highly selective).
        search_token = doi_uuid.split('-')[0] if '-' in doi_uuid else doi_uuid
        csw_params = {
            'service': 'CSW',
            'version': '2.0.2',
            'request': 'GetRecords',
            'resultType': 'results',
            'outputSchema': 'http://www.isotc211.org/2005/gmd',
            'elementSetName': 'full',
            'constraintLanguage': 'CQL_TEXT',
            'constraint_language_version': '1.1.0',
            'constraint': "AnyText like '%{}%'".format(search_token),
        }
        csw_url = 'https://data-search.nerc.ac.uk/geonetwork/srv/eng/csw?' + urlencode(csw_params)
        csw_resp = self._get_with_retry(csw_url, headers={'Accept': 'application/xml'})
        csw_text = csw_resp.text

        file_id = None
        m = re.search(r'<gco:CharacterString>([0-9a-fA-F-]{36})</gco:CharacterString>', csw_text)
        if m:
            file_id = m.group(1)
        if not file_id:
            return {"error": "CSW 搜索响应中未找到 GeoNetwork 内部记录 ID，无法完成映射"}

        # --- 3. Final single native RESTful API: GeoNetwork records formatters/xml ---
        rest_url = 'https://data-search.nerc.ac.uk/geonetwork/srv/api/records/{}/formatters/xml'.format(file_id)
        rest_resp = self._get_with_retry(rest_url, headers={'Accept': 'application/xml'})
        return {
            'source': 'NERC EDS National Geoscience Data Centre (via NERC Data Catalogue Service GeoNetwork)',
            'format': 'xml',
            'data': rest_resp.text,
        }

